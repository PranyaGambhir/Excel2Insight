def _safe_markdown(text: str) -> str:
    """Markdown -> HTML with any raw HTML escaped (LLM output and user edits are untrusted)."""
    escaped = html.escape(text, quote=False)
    escaped = re.sub(r"^(\s*)&gt;", r"\1>", escaped, flags=re.M)   # keep '> quote' blocks working
    return md.markdown(escaped, extensions=["extra", "sane_lists"])


def _table(df: pd.DataFrame | None, max_rows: int = 60) -> str:
    if df is None or df.empty:
        return ""
    return df.head(max_rows).to_html(classes="tbl", index=False, border=0, float_format=lambda x: f"{x:,.3f}".rstrip("0").rstrip("."))


def build_html_report(*, filename: str, profile: dict, analytics: dict, figures: dict,
                      insights_md: str, insight_source: str, cleaning_log: list[str] | None = None,
                      clean_shape: tuple[int, int] | None = None, title: str = "Data Analytics Report",
                      embed_plotlyjs: bool = False) -> str:
    """embed_plotlyjs=False loads Plotly from a CDN (small file); True embeds it (~4 MB, works offline)."""
    charts = []
    for i, (name, fig) in enumerate(figures.items()):
        include = ("cdn" if not embed_plotlyjs else True) if i == 0 else False
        charts.append((name, fig.to_html(full_html=False, include_plotlyjs=include, config={"displaylogo": False})))

    tables = {
        "types": _table(profile["types"]),
        "missing": _table(profile["missing"]),
        "outliers": _table(profile["outliers"]),
        "numeric": _table(analytics["descriptive"]["numeric"]) or "<p>No numeric columns.</p>",
        "categorical": _table(analytics["descriptive"]["categorical"]),
        "correlations": _table(analytics["correlation"]["pairs"]),
    }
    env = Environment(autoescape=select_autoescape(["html"]))
    return env.from_string(TEMPLATE).render(
        title=title, filename=filename, generated=datetime.now().strftime("%d %b %Y %H:%M"),
        insight_source=insight_source, profile=profile, clean_shape=clean_shape, cleaning_log=cleaning_log or [],
        tables=tables, charts=charts,
        insights_html=_safe_markdown(insights_md),
    )
